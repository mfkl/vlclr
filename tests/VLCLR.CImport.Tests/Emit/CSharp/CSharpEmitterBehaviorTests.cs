using VLCLR.CImport.Emit;
using VLCLR.CImport.Merge;
using VLCLR.CImport.Model;
using VLCLR.CImport.Naming;
using VLCLR.CImport.Tests.Emit.CSharp.Cases;
using static VLCLR.CImport.Tests.Emit.CSharp.Cases.Ir;

namespace VLCLR.CImport.Tests.Emit.CSharp;

public class CSharpEmitterBehaviorTests
{
    private static CSharpEmitResult Emit(MergedSnapshot merged, INameMap? names = null)
        => new CSharpEmitter(merged, names ?? new TestNameMap(), new CSharpEmitOptions("libvlccore")).Emit();

    private static MergedSnapshot Merge(Func<bool, Snapshot> build)
        => AbiMerger.Merge(build(true), build(false));

    [Fact]
    public void Error_diagnostics_stop_emission()
    {
        var merged = AbiMerger.Merge(
            Snapshot(true, types: [Struct("only_win_t", "vlc_a.h", 4, 4, F("x", Int, 0))]),
            Snapshot(false));

        var error = Assert.Throws<InvalidOperationException>(() => Emit(merged));
        Assert.Contains("only_win_t", error.Message);
    }

    [Fact]
    public void Warning_diagnostics_are_ignored()
    {
        var merged = CSharpCases.Merged("unsupported");
        Assert.Contains(merged.Diagnostics, d => d.Severity == DiagnosticSeverity.Warning);
        Assert.NotEmpty(Emit(merged, CSharpCases.NameMap("unsupported")).Files);
    }

    [Fact]
    public void Writes_one_file_per_header_plus_the_helpers()
    {
        var files = CSharpGeneration("divergent").Files;

        Assert.Equal(["CImport.g.cs", "VlcEs.g.cs", "VlcFilter.g.cs", "VlcPicture.g.cs"], files.Keys.ToArray());
        Assert.StartsWith("// <auto-generated> from vlc_es.h @ vlc dc69496e by VLCLR.CImport. Do not edit.\n", files["VlcEs.g.cs"]);
        Assert.Contains("namespace Test.Interop;", files["VlcEs.g.cs"]);
    }

    [Fact]
    public void Anonymous_records_used_only_as_anonymous_members_are_not_emitted()
    {
        var text = string.Concat(CSharpGeneration("divergent").Files.Values);
        Assert.DoesNotContain("Anon0", text);
        Assert.Contains("struct VideoFormatDovi", text);

        var unions = string.Concat(CSharpGeneration("unions").Files.Values);
        Assert.DoesNotContain("Anon0", unions);
        Assert.Contains("struct RecStats", unions);
    }

    [Fact]
    public void Opaque_records_have_no_layout_and_no_size()
    {
        var text = CSharpGeneration("opaque").Files["VlcObjects.g.cs"];
        Assert.Contains("public partial struct VlcObject { }", text);
        Assert.DoesNotContain("SizeOf => 0", text);
    }

    [Fact]
    public void Skipped_symbols_carry_kind_header_and_reason()
    {
        var skipped = CSharpGeneration("functions").Skipped;

        Assert.Contains(new SkippedSymbol("vlc_msg_Log", "vlc_fn.h", "function", "variadic"), skipped);
        Assert.Contains(new SkippedSymbol("vlc_inline_Foo", "vlc_fn.h", "function", "static inline (not exported)"), skipped);
        Assert.Contains(new SkippedSymbol("vlc_priv_Bar", "vlc_fn.h", "function", "not exported"), skipped);
        Assert.Contains(skipped, s => s.Symbol == "vlc_diff_Foo" && s.Reason == "signature differs between ABIs");
        Assert.Contains(skipped, s => s.Symbol == "vlc_ld_Get" && s.Reason.Contains("long double"));
    }

    [Fact]
    public void Unsupported_members_are_skipped_one_by_one()
    {
        var skipped = CSharpGeneration("unsupported").Skipped.Where(s => s.Kind == "field").Select(s => s.Symbol).ToList();

        Assert.Equal(
            ["weird_t.c16", "weird_t.diff", "weird_t.e_missing", "weird_t.ld", "weird_t.missing", "weird_t.p_missing", "weird_t.pp_arr", "weird_t.v", "weird_t.wc", "weird_t.wide"],
            skipped);
        Assert.Contains("public int Ok;", CSharpGeneration("unsupported").Files["VlcWeird.g.cs"]);
    }

    [Fact]
    public void Flexible_and_divergent_size_arrays_are_skipped()
    {
        var skipped = CSharpGeneration("arrays").Skipped;
        Assert.Contains(skipped, s => s.Symbol == "arrays_t.flex" && s.Reason == "flexible array member");
        Assert.Contains(skipped, s => s.Symbol == "dv_holder_t.dvs" && s.Reason.StartsWith("array of record 'dv_t'", StringComparison.Ordinal));
    }

    [Fact]
    public void Plain_char_bitfields_are_skipped()
    {
        var merged = Merge(w => Snapshot(w, types: [Struct("a_t", "vlc_a.h", 4, 4, Bits("c", CharT, 0, 4), Bits("u", U8, 4, 4))]));

        var result = Emit(merged);

        Assert.Contains(new SkippedSymbol("a_t.c", "vlc_a.h", "field", "plain char bitfield: its signedness depends on the target"), result.Skipped);
        Assert.Contains("public byte U", result.Files["VlcA.g.cs"]);
    }

    [Fact]
    public void Bitfield_accessors_that_pick_a_per_abi_offset_are_inlined()
    {
        var text = string.Concat(CSharpGeneration("divergent").Files.Values);

        Assert.Contains("    [MethodImpl(MethodImplOptions.AggressiveInlining)] readonly get => unchecked((uint)CImportHelpers.ReadBits(in this, (OperatingSystem.IsWindows() ? 32 : 16), 7));", text);
        Assert.Contains("    [MethodImpl(MethodImplOptions.AggressiveInlining)] set => CImportHelpers.WriteBits(ref this, (OperatingSystem.IsWindows() ? 32 : 16), 7, (ulong)value);", text);
    }

    [Fact]
    public void Enum_value_and_type_decisions_are_reported()
    {
        var result = CSharpGeneration("enums");
        var text = result.Files["VlcEnums.g.cs"];

        Assert.Contains("public enum Sign : int", text);          // windows int, sysv unsigned int: signed wins
        Assert.Contains("public enum SignBig : uint", text);      // 2147483648 does not fit int
        Assert.Contains("public enum Big : ulong", text);
        Assert.Contains("BigMax = 18446744073709551615", text);
        Assert.Contains("ANeg = -1", text);
        Assert.Contains("public enum Width : byte", text);
        Assert.DoesNotContain("DvDiff", text);
        Assert.DoesNotContain("enum Size", text);
        Assert.Contains("public const uint BigLimit = 4294967295;", text);
        Assert.Contains(result.Skipped, s => s.Kind == "enum member" && s.Symbol == "div_val_e.DV_DIFF");
        Assert.Contains(result.Skipped, s => s.Kind == "enum" && s.Symbol == "size_e");
    }

    [Fact]
    public void Values_that_do_not_fit_their_constant_type_are_skipped()
    {
        var skipped = CSharpGeneration("constants").Skipped;
        Assert.Contains(skipped, s => s.Kind == "constant" && s.Symbol == "TOO_BIG");
    }

    [Fact]
    public void Constants_land_in_the_struct_when_the_class_name_is_a_record()
    {
        var files = CSharpGeneration("constants").Files;
        Assert.Contains("public partial struct Point", files["VlcConst2.g.cs"]);
        Assert.Contains("public static partial class Constants", files["VlcConst.g.cs"]);
    }

    [Fact]
    public void Functions_land_in_the_struct_when_the_class_name_is_a_record()
    {
        Assert.Contains("public unsafe partial struct VideoFormat", CSharpGeneration("functions").Files["VlcFn2.g.cs"]);
        Assert.Contains("public unsafe partial struct VlcObject", CSharpGeneration("opaque").Files["VlcObjects.g.cs"]);
    }

    [Fact]
    public void Colliding_member_names_throw()
    {
        var merged = Merge(w => Snapshot(w, types: [Struct("a_t", "vlc_a.h", 8, 4, F("x_y", Int, 0), F("xY", Int, 4))]));

        var error = Assert.Throws<InvalidOperationException>(() => Emit(merged));
        Assert.Contains("produced twice", error.Message);
    }

    [Fact]
    public void Colliding_inline_array_type_names_throw()
    {
        var merged = Merge(w => Snapshot(w, types:
        [
            Struct("a_t", "vlc_a.h", 8, 4, F("data", Arr(Int, 1), 0), F("data_array", Int, 4)),
        ]));

        var error = Assert.Throws<InvalidOperationException>(() => Emit(merged));
        Assert.Contains("DataArray", error.Message);
    }

    [Fact]
    public void A_class_that_is_an_enum_name_throws()
    {
        var merged = Merge(w => Snapshot(w,
            enums: [Enumeration("vlc_mode_e", "vlc_a.h", BuiltinType.Int, ("A", 0))],
            functions: [Function("vlc_mode_Get", "vlc_a.h", Int)]));

        Assert.Throws<InvalidOperationException>(() => Emit(merged, new TestNameMap(functionOverrides: new Dictionary<string, QualifiedName> { ["vlc_mode_Get"] = new("VlcMode", "Get") })));
    }

    [Fact]
    public void Two_headers_with_the_same_file_stem_throw()
    {
        var merged = Merge(w => Snapshot(w, types:
        [
            Struct("a_t", "vlc_a.h", 4, 4, F("x", Int, 0)),
            Struct("b_t", "vlc_a.hpp", 4, 4, F("x", Int, 0)),
        ]));

        Assert.Throws<InvalidOperationException>(() => Emit(merged));
    }

    [Fact]
    public void The_compilation_helper_reports_warnings_and_generator_diagnostics()
    {
        var unusedVariable = CSharpCompilationHelper.Compile([new("a.cs", "class A { void M() { int x = 1; } }")]);
        Assert.NotEmpty(unusedVariable.Diagnostics);

        var badImport = CSharpCompilationHelper.Compile([new("a.cs", """
            using System.Runtime.InteropServices;
            public static partial class B
            {
                [LibraryImport("x")]
                public static partial string M(string s);
            }
            """)]);
        Assert.Contains(badImport.Diagnostics, d => d.Contains("SYSLIB1051", StringComparison.Ordinal) || d.Contains("SYSLIB1050", StringComparison.Ordinal));
    }

    private static CSharpEmitResult CSharpGeneration(string name)
        => Emit(CSharpCases.Merged(name), CSharpCases.NameMap(name));
}
