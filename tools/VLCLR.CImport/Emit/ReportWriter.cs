using System.Text;
using VLCLR.CImport.Merge;

namespace VLCLR.CImport.Emit;

/// <summary>
/// cimport-report.md: what was selected from the headers but is not in the
/// generated C#, where the two ABIs disagree, and what exists on one only.
/// </summary>
public static class ReportWriter
{
    public static string Write(MergedSnapshot merged, IReadOnlyList<SkippedSymbol> emitSkipped)
    {
        var sb = new StringBuilder();
        sb.Append($"# CImport report\n\n");
        sb.Append($"Generated by VLCLR.CImport from VLC {merged.VlcCommit[..Math.Min(8, merged.VlcCommit.Length)]} ({string.Join(", ", merged.Abis)}). Do not edit.\n\n");
        sb.Append($"{merged.Types.Count} records, {merged.Enums.Count} enums, {merged.Functions.Count} functions, {merged.Constants.Count} constants selected.\n");

        sb.Append("\n## Not emitted\n\n");
        if (emitSkipped.Count == 0)
        {
            sb.Append("Nothing.\n");
        }
        else
        {
            sb.Append("| Symbol | Kind | Header | Reason |\n|---|---|---|---|\n");
            foreach (var s in emitSkipped)
                sb.Append($"| `{s.Symbol}` | {s.Kind} | {s.Header} | {Cell(s.Reason)} |\n");
        }

        sb.Append("\n## Not extracted\n\n");
        if (merged.Skipped.Count == 0)
        {
            sb.Append("Nothing.\n");
        }
        else
        {
            sb.Append("| Symbol | Kind | Header | Reason | ABIs |\n|---|---|---|---|---|\n");
            foreach (var s in merged.Skipped)
                sb.Append($"| `{s.Declaration.Name}` | {s.Declaration.Kind} | {s.Declaration.Header} | {Cell(s.Declaration.Reason)} | {string.Join(", ", s.Abis)} |\n");
        }

        sb.Append("\n## Differences between ABIs\n\n");
        var warnings = merged.Diagnostics.Where(d => d.Severity == DiagnosticSeverity.Warning).ToList();
        if (warnings.Count == 0)
        {
            sb.Append("None beyond sizes and offsets.\n");
        }
        else
        {
            sb.Append("| Symbol | Difference |\n|---|---|\n");
            foreach (var d in warnings)
                sb.Append($"| `{d.Symbol}` | {Cell(d.Message)} |\n");
        }

        sb.Append("\n## Platform-specific\n\n");
        if (merged.Platforms.Count == 0)
        {
            sb.Append("Nothing: every symbol exists on every ABI.\n");
        }
        else
        {
            sb.Append("Symbols that exist on some ABIs only; the C# marks them with `[SupportedOSPlatform]` or `[UnsupportedOSPlatform]`.\n\n");
            sb.Append("| Symbol | Only on |\n|---|---|\n");
            foreach (var (name, abis) in merged.Platforms.OrderBy(p => p.Key, StringComparer.Ordinal))
                sb.Append($"| `{name}` | {string.Join(", ", abis)} |\n");
        }

        var divergent = merged.Types.Where(t => t.Size is { IsUniform: false }).Select(t => $"`{t.Name}` ({t.Size})").ToList();
        if (divergent.Count > 0)
            sb.Append($"\nRecords whose size differs (windows | sysv): {string.Join(", ", divergent)}.\n");

        return sb.ToString();
    }

    private static string Cell(string text) => text.Replace("|", "\\|").Replace("\n", " ");
}
