using System.Globalization;
using System.Text;
using VLCLR.CImport.Merge;
using VLCLR.CImport.Model;

namespace VLCLR.CImport.Emit;

/// <summary>Headers to include (in order) and extra per-ABI lines placed before them.</summary>
/// <param name="Headers">Header names in include order, e.g. <c>vlc_common.h</c>.</param>
/// <param name="Prelude">Lines per ABI name (<see cref="Abis.Windows"/>, <see cref="Abis.SysV"/>), emitted under <c>#ifdef _WIN32</c> / <c>#else</c>.</param>
public sealed record ProbeOptions(IReadOnlyList<string> Headers, IReadOnlyDictionary<string, IReadOnlyList<string>> Prelude);

/// <summary>
/// Writes a C++17 translation unit of <c>static_assert</c>s that compiles only when
/// the real compiler agrees with the snapshot: record sizes, alignments, member
/// offsets, enum values and integer constants, per ABI. Compile-only, never linked.
/// </summary>
/// <remarks>
/// Bitfields get no offset assertion: <c>offsetof</c> does not apply to them and
/// there is no C++17 constant expression that can observe their position. The
/// record's size and alignment and the offsets of the members around them are still
/// checked, and the generated layout tests verify the bit positions on the C# side.
/// </remarks>
public sealed class ProbeEmitter(MergedSnapshot merged, ProbeOptions options)
{
    private readonly StringBuilder _sb = new();
    private readonly Dictionary<string, string> _aliases = new(StringComparer.Ordinal);
    private readonly List<string> _aliasLines = [];

    public string Emit()
    {
        _sb.Clear();
        _aliases.Clear();
        _aliasLines.Clear();

        var records = EmittedRecords.Select(merged);
        foreach (var record in records.Where(r => r.IsAnonymous))
            TypeExpression(record);

        WriteHeader();
        WritePrelude();
        WriteMacros();
        WriteAliases();
        WriteRecords(records);
        WriteEnums();
        WriteConstants();
        return _sb.ToString();
    }

    private void Line(string text = "") => _sb.Append(text).Append('\n');

    private void WriteHeader()
    {
        Line("// <auto-generated>");
        Line($"// Generated by VLCLR.CImport from the VLC headers at commit {merged.VlcCommit}. Do not edit.");
        Line("// Compile-only ABI probe: it fails to compile when a size, offset or value in the generated");
        Line("// C# bindings disagrees with the C compiler. Build with: cl /std:c++17 /TP /c, or g++ -std=c++17 -c.");
        Line("// </auto-generated>");
        Line();
        Line("#include <cstddef>");
        Line("#include <atomic>");
        Line("#include <cstdio>");
        Line("#include <cstdlib>");
        Line("#include <cstring>");
        Line("#include <ctime>");
        Line("#include <type_traits>");
        Line("#include <sys/types.h>");
        Line("#ifdef _MSC_VER");
        Line("#include <BaseTsd.h>");
        Line();
        Line("typedef SSIZE_T ssize_t;");
        Line("#endif");
        Line("#define restrict __restrict");
        Line();
    }

    private void WritePrelude()
    {
        var windows = PreludeLines(Abis.Windows);
        var sysv = PreludeLines(Abis.SysV);
        if (windows.Count > 0 || sysv.Count > 0)
        {
            Line("#ifdef _WIN32");
            foreach (var l in windows)
                Line(l);
            Line("#else");
            foreach (var l in sysv)
                Line(l);
            Line("#endif");
            Line();
        }

        foreach (var header in options.Headers)
            Line($"#include <{header}>");
        Line();
    }

    private IReadOnlyList<string> PreludeLines(string abi)
        => options.Prelude.TryGetValue(abi, out var lines) ? lines : [];

    private void WriteMacros()
    {
        Line("static_assert(sizeof(void *) == 8, \"VLCLR currently targets the 64-bit VLC ABI\");");
        Line();
        Line("#ifdef _WIN32");
        Line("#define VLCLR_ABI(windows, sysv) windows");
        Line("#else");
        Line("#define VLCLR_ABI(windows, sysv) sysv");
        Line("#endif");
        Line("#define VLCLR_SIZE(type, label, expected) \\");
        Line("    static_assert(sizeof(type) == (expected), \"VLCLR size mismatch: \" label)");
        Line("#define VLCLR_ALIGN(type, label, expected) \\");
        Line("    static_assert(alignof(type) == (expected), \"VLCLR alignment mismatch: \" label)");
        Line("#define VLCLR_OFFSET(type, label, field, expected) \\");
        Line("    static_assert(offsetof(type, field) == (expected), \"VLCLR offset mismatch: \" label \".\" #field)");
        Line("#define VLCLR_VALUE(name, expected) \\");
        Line("    static_assert((long long)(name) == (expected), \"VLCLR value mismatch: \" #name)");
        Line("#define VLCLR_UVALUE(name, expected) \\");
        Line("    static_assert((unsigned long long)(name) == (expected), \"VLCLR value mismatch: \" #name)");
        Line();
    }

    private void WriteAliases()
    {
        if (_aliasLines.Count == 0)
            return;
        Line("// Anonymous records used as the type of a named field.");
        foreach (var l in _aliasLines)
            Line(l);
        Line();
    }

    private void WriteRecords(IReadOnlyList<MergedType> records)
    {
        foreach (var type in records)
        {
            var expr = TypeExpression(type);
            var label = $"\"{Escape(type.Name)}\"";
            Line($"// {type.Name}");
            Line($"VLCLR_SIZE({expr}, {label}, {Plain(type.Size!)});");
            Line($"VLCLR_ALIGN({expr}, {label}, {Plain(type.Alignment!)});");
            foreach (var member in type.Members.Where(m => !m.IsBitfield))
                Line($"VLCLR_OFFSET({expr}, {label}, {member.Name}, {Plain(member.Offset)});");
            Line();
        }
    }

    private void WriteEnums()
    {
        foreach (var e in merged.Enums.OrderBy(e => e.Name, StringComparer.Ordinal))
        {
            if (e.Members.Count == 0)
                continue;
            var unsigned = e.UnderlyingType.Values.Any(IsUnsigned64);
            Line($"// enum {e.Name}");
            foreach (var m in e.Members)
                Line($"{(unsigned ? "VLCLR_UVALUE" : "VLCLR_VALUE")}({m.Name}, {Value(m.Value.Values, unsigned)});");
            Line();
        }
    }

    private void WriteConstants()
    {
        var constants = merged.Constants
            .Where(c => c is { Kind: ConstantKind.Integer, Integer: not null } && c.Integer.Values.All(v => v is not null))
            .OrderBy(c => c.Name, StringComparer.Ordinal)
            .ToList();
        if (constants.Count == 0)
            return;

        Line("// Integer constants");
        foreach (var c in constants)
        {
            var unsigned = c.Type.Values.Any(IsUnsigned64);
            var values = c.Integer!.Values.Select(v => v!.Value);
            Line($"{(unsigned ? "VLCLR_UVALUE" : "VLCLR_VALUE")}({c.Name}, {Value(values, unsigned)});");
        }
        Line();
    }

    private static bool IsUnsigned64(TypeRef type)
        => type.Desugar() is { Kind: TypeRefKind.Builtin, Builtin: BuiltinType.ULong or BuiltinType.ULongLong };

    /// <summary>The C++ spelling of a record type: its name, or an alias for anonymous records.</summary>
    private string TypeExpression(MergedType type)
    {
        if (!type.IsAnonymous)
            return type.Name;
        if (_aliases.TryGetValue(type.Name, out var existing))
            return existing;

        var (owner, field) = merged.Types
            .SelectMany(t => t.Fields.Where(f => !f.IsAnonymousMember).Select(f => (Owner: t, Field: f)))
            .FirstOrDefault(x => EmittedRecords.ElementRecord(x.Field.Type) == type.Name);

        string alias;
        if (owner is null)
        {
            // Not a named field's type: an anonymous member. Reached only through its parent.
            alias = type.Parent is { } parent && merged.FindType(parent) is { } p ? TypeExpression(p) : type.Name;
            _aliases[type.Name] = alias;
            return alias;
        }

        alias = "cimport_" + Sanitize(type.Name);
        _aliases[type.Name] = alias;
        var ownerExpr = TypeExpression(owner);
        _aliasLines.Add($"using {alias} = std::remove_all_extents_t<decltype({ownerExpr}::{field.Name})>;");
        return alias;
    }

    private static string Sanitize(string name)
    {
        var sb = new StringBuilder();
        foreach (var ch in name.Replace("::", "_").Replace("@", "anon"))
            sb.Append(char.IsAsciiLetterOrDigit(ch) || ch == '_' ? ch : '_');
        return sb.ToString();
    }

    private static string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");

    /// <summary>Sizes, alignments and offsets: plain decimal, one value or a per-ABI choice.</summary>
    private static string Plain(PerAbi<long> value)
    {
        var text = value.Values.Select(v => v.ToString(CultureInfo.InvariantCulture)).ToList();
        return value.IsUniform ? text[0] : $"VLCLR_ABI({text[0]}, {text[1]})";
    }

    private static string Value(IEnumerable<long> values, bool unsigned = false)
    {
        var list = values.ToList();
        if (list.Distinct().Count() == 1)
            return Literal(list[0], unsigned);
        return $"VLCLR_ABI({Literal(list[0], unsigned)}, {Literal(list[1], unsigned)})";
    }

    private static string Literal(long value, bool unsigned)
    {
        if (unsigned)
            return unchecked((ulong)value).ToString(CultureInfo.InvariantCulture) + "ULL";
        if (value == long.MinValue)
            return "(-9223372036854775807LL - 1)";
        return value.ToString(CultureInfo.InvariantCulture) + "LL";
    }
}
