using System.Globalization;
using System.Text;
using VLCLR.CImport.Merge;
using VLCLR.CImport.Model;

namespace VLCLR.CImport.Emit;

/// <summary>Headers to include (in order) and what to place before them.</summary>
/// <param name="Headers">Header names in include order, e.g. <c>vlc_common.h</c>.</param>
/// <param name="Prelude">Lines per ABI name (<see cref="Abis.Windows"/>, <see cref="Abis.SysV"/>), emitted under <c>#ifdef _WIN32</c> / <c>#else</c>.</param>
public sealed record ProbeOptions(IReadOnlyList<string> Headers, IReadOnlyDictionary<string, IReadOnlyList<string>> Prelude)
{
    /// <summary>Preprocessor definitions per ABI name (<c>NAME</c> or <c>NAME=VALUE</c>), as extract parsed with.</summary>
    public IReadOnlyDictionary<string, IReadOnlyList<string>> Defines { get; init; } = new Dictionary<string, IReadOnlyList<string>>();

    /// <summary>Headers left out, with the symbols they declare: they are C only.</summary>
    public IReadOnlyList<string> ExcludeHeaders { get; init; } = [];

    /// <summary>Headers MSVC cannot parse (POSIX ones): included, and their symbols checked, by the other compilers only.</summary>
    public IReadOnlyList<string> MsvcExcludeHeaders { get; init; } = [];
}

/// <summary>
/// Writes a C11 translation unit of <c>_Static_assert</c>s that compiles only when
/// the real compiler agrees with the snapshot: record sizes, alignments, member
/// offsets, enum values and integer constants, per ABI. Compile-only, never linked.
/// C, not C++: VLC's headers declare some types differently for C++
/// (<c>vlc_threads.h</c>), and C++ scopes the tagged records declared inside
/// another record, which C does not.
/// </summary>
/// <remarks>
/// Bitfields get no offset assertion: <c>offsetof</c> does not apply to them and
/// there is no C constant expression that can observe their position. The
/// record's size and alignment and the offsets of the members around them are still
/// checked, and the generated layout tests verify the bit positions on the C# side.
/// Anonymous records that type a named field are named with <c>__typeof__</c>,
/// which GCC, Clang and MSVC (C17 and later) all accept.
/// </remarks>
public sealed class ProbeEmitter(MergedSnapshot merged, ProbeOptions options)
{
    private readonly StringBuilder _sb = new();
    private readonly Dictionary<string, string> _aliases = new(StringComparer.Ordinal);
    private readonly List<(string? Condition, string Line)> _aliasLines = [];
    private HashSet<string>? _typedefNames;

    public string Emit()
    {
        _sb.Clear();
        _aliases.Clear();
        _aliasLines.Clear();

        var records = EmittedRecords.Select(merged).Where(r => Condition(r.Name, r.Header) != Never).ToList();
        foreach (var record in records.Where(r => r.IsAnonymous))
            TypeExpression(record);

        WriteHeader();
        WritePrelude();
        WriteMacros();
        WriteAliases();
        WriteRecords(records);
        WriteEnums();
        WriteConstants();
        return _sb.ToString();
    }

    private void Line(string text = "") => _sb.Append(text).Append('\n');

    private void WriteHeader()
    {
        Line("// <auto-generated>");
        Line($"// Generated by VLCLR.CImport from the VLC headers at commit {merged.VlcCommit}. Do not edit.");
        Line("// Compile-only ABI probe: it fails to compile when a size, offset or value in the generated");
        Line("// C# bindings disagrees with the C compiler. Build with: cc -std=gnu11 -c, or");
        Line("// cl /std:clatest /experimental:c11atomics /TC /c.");
        Line("// </auto-generated>");
        Line();
        WriteDefines();
        WriteAbiPrelude();
        // The MSVC CRT has no ssize_t nor mode_t, and hides off_t from C. VLC
        // builds with mingw-w64: these are its types, off_t 64-bit with
        // _FILE_OFFSET_BITS=64.
        Line("#ifdef _MSC_VER");
        Line("#define _OFF_T_DEFINED");
        Line("typedef long long _off_t;");
        Line("typedef long long off_t;");
        Line("typedef unsigned short mode_t;");
        Line("#include <BaseTsd.h>");
        Line("typedef SSIZE_T ssize_t;");
        Line("#endif");
        Line("#include <stddef.h>");
        Line("#include <stdio.h>");
        Line("#include <stdlib.h>");
        Line("#include <string.h>");
        Line("#include <time.h>");
        Line("#include <sys/types.h>");
        Line();
    }

    /// <summary>
    /// The manifest's per-ABI prelude, first, as extract places it: guards such
    /// as <c>_OFF_T_DEFINED</c> must precede the system headers.
    /// </summary>
    private void WriteAbiPrelude() => WritePerAbi(abi => [.. PreludeLines(abi)]);

    /// <summary>The definitions extract parsed with, before any header (<c>_FILE_OFFSET_BITS</c> changes system types).</summary>
    private void WriteDefines() => WritePerAbi(DefineLines);

    /// <summary>
    /// Lines every ABI has, then the others under <c>#if defined(_WIN32)</c> /
    /// <c>#elif defined(__APPLE__)</c> / <c>#else</c> (sysv).
    /// </summary>
    private void WritePerAbi(Func<string, List<string>> linesOf)
    {
        var lines = Abis.All.ToDictionary(abi => abi, linesOf);
        var common = lines.Values.Aggregate((a, b) => [.. a.Intersect(b)]);
        foreach (var l in common)
            Line(l);
        if (lines.Values.Any(l => l.Count > common.Count))
        {
            Line($"#if {Abis.CTest(Abis.Windows)}");
            foreach (var l in lines[Abis.Windows].Except(common))
                Line(l);
            Line($"#elif {Abis.CTest(Abis.Darwin)}");
            foreach (var l in lines[Abis.Darwin].Except(common))
                Line(l);
            Line("#else");
            foreach (var l in lines[Abis.SysV].Except(common))
                Line(l);
            Line("#endif");
        }
        if (lines.Values.Any(l => l.Count > 0))
            Line();
    }

    private List<string> DefineLines(string abi)
        => [.. (options.Defines.TryGetValue(abi, out var defines) ? defines : [])
            .Select(d => d.Split('=', 2) is [var name, var value] ? $"#define {name} {value}" : $"#define {d}")];

    private void WritePrelude()
    {
        foreach (var header in options.Headers)
            Guarded(Condition(null, header), () => Line($"#include <{header}>"));
        Line();
    }

    private const string Never = "0";

    /// <summary>
    /// The preprocessor condition a symbol's checks need: <see cref="Never"/>
    /// for a C-only header, <c>!defined(_MSC_VER)</c> for a header MSVC cannot
    /// parse and for the system headers' own types (extracted from mingw-w64's,
    /// not MSVC's), <c>defined(_WIN32)</c> or its negation for a symbol of one
    /// ABI; null when it always applies.
    /// </summary>
    private string? Condition(string? cName, string header)
    {
        // C cannot name the compiler's own records (__va_list_tag on sysv).
        if (options.ExcludeHeaders.Contains(header, StringComparer.Ordinal) || header.StartsWith('<'))
            return Never;
        var conditions = new List<string>();
        if (options.MsvcExcludeHeaders.Contains(header, StringComparer.Ordinal)
            || (cName is not null && !options.Headers.Contains(header, StringComparer.Ordinal)))
            conditions.Add("!defined(_MSC_VER)");
        if (cName is not null && merged.PlatformsOf(cName) is { } platforms)
            conditions.Add(platforms.Count == 1 ? Abis.CTest(platforms[0]) : $"({string.Join(" || ", platforms.Select(Abis.CTest))})");
        return conditions.Count == 0 ? null : string.Join(" && ", conditions);
    }

    private void Guarded(string? condition, Action write)
    {
        if (condition == Never)
            return;
        if (condition is not null)
            Line($"#if {condition}");
        write();
        if (condition is not null)
            Line("#endif");
    }

    private IReadOnlyList<string> PreludeLines(string abi)
        => options.Prelude.TryGetValue(abi, out var lines) ? lines : [];

    private void WriteMacros()
    {
        Line("_Static_assert(sizeof(void *) == 8, \"VLCLR currently targets the 64-bit VLC ABI\");");
        Line();
        Line($"#if {Abis.CTest(Abis.Windows)}");
        Line("#define VLCLR_ABI(windows, sysv, darwin) windows");
        Line($"#elif {Abis.CTest(Abis.Darwin)}");
        Line("#define VLCLR_ABI(windows, sysv, darwin) darwin");
        Line("#else");
        Line("#define VLCLR_ABI(windows, sysv, darwin) sysv");
        Line("#endif");
        Line("#define VLCLR_SIZE(type, label, expected) \\");
        Line("    _Static_assert(sizeof(type) == (expected), \"VLCLR size mismatch: \" label)");
        Line("#define VLCLR_ALIGN(type, label, expected) \\");
        Line("    _Static_assert(_Alignof(type) == (expected), \"VLCLR alignment mismatch: \" label)");
        Line("#define VLCLR_OFFSET(type, label, field, expected) \\");
        Line("    _Static_assert(offsetof(type, field) == (expected), \"VLCLR offset mismatch: \" label \".\" #field)");
        Line("#define VLCLR_VALUE(name, expected) \\");
        Line("    _Static_assert((long long)(name) == (expected), \"VLCLR value mismatch: \" #name)");
        Line("#define VLCLR_UVALUE(name, expected) \\");
        Line("    _Static_assert((unsigned long long)(name) == (expected), \"VLCLR value mismatch: \" #name)");
        Line();
    }

    private void WriteAliases()
    {
        if (_aliasLines.Count == 0)
            return;
        Line("// Anonymous records used as the type of a named field.");
        foreach (var (condition, l) in _aliasLines)
            Guarded(condition, () => Line(l));
        Line();
    }

    private void WriteRecords(IReadOnlyList<MergedType> records)
    {
        foreach (var type in records)
        {
            var expr = TypeExpression(type);
            var label = $"\"{Escape(type.Name)}\"";
            Line($"// {type.Name}");
            Guarded(Condition(type.Name, type.Header), () =>
            {
                Line($"VLCLR_SIZE({expr}, {label}, {Plain(type.Size!)});");
                Line($"VLCLR_ALIGN({expr}, {label}, {Plain(type.Alignment!)});");
                foreach (var member in type.Members.Where(m => !m.IsBitfield))
                    Line($"VLCLR_OFFSET({expr}, {label}, {member.Name}, {Plain(member.Offset)});");
            });
            Line();
        }
    }

    private void WriteEnums()
    {
        foreach (var e in merged.Enums.OrderBy(e => e.Name, StringComparer.Ordinal))
        {
            if (e.Members.Count == 0 || Condition(e.Name, e.Header) == Never)
                continue;
            var unsigned = e.UnderlyingType.Values.Any(IsUnsigned64);
            Line($"// enum {e.Name}");
            Guarded(Condition(e.Name, e.Header), () =>
            {
                foreach (var m in e.Members)
                    Line($"{(unsigned ? "VLCLR_UVALUE" : "VLCLR_VALUE")}({m.Name}, {Value(m.Value.Values, unsigned)});");
            });
            Line();
        }
    }

    private void WriteConstants()
    {
        var constants = merged.Constants
            .Where(c => c is { Kind: ConstantKind.Integer, Integer: not null } && c.Integer.Values.All(v => v is not null))
            .Where(c => Condition(c.Name, c.Header) != Never)
            .OrderBy(c => c.Name, StringComparer.Ordinal)
            .ToList();
        if (constants.Count == 0)
            return;

        // Each under #ifdef: some are defined for one architecture only
        // (VLC_CPU_SSE2 on x86), and the snapshots are x86-64's.
        Line("// Integer constants");
        foreach (var c in constants)
        {
            var unsigned = c.Type.Values.Any(IsUnsigned64);
            var values = c.Integer!.Values.Select(v => v!.Value);
            var condition = Condition(c.Name, c.Header) is { } platform ? $"defined({c.Name}) && {platform}" : $"defined({c.Name})";
            Guarded(condition, () => Line($"{(unsigned ? "VLCLR_UVALUE" : "VLCLR_VALUE")}({c.Name}, {Value(values, unsigned)});"));
        }
        Line();
    }

    private static bool IsUnsigned64(TypeRef type)
        => type.Desugar() is { Kind: TypeRefKind.Builtin, Builtin: BuiltinType.ULong or BuiltinType.ULongLong };

    /// <summary>
    /// The C spelling of a record type: its typedef name, <c>struct tag</c> when
    /// no typedef of that name exists, or an alias for anonymous records.
    /// </summary>
    private string TypeExpression(MergedType type)
    {
        if (!type.IsAnonymous)
        {
            _typedefNames ??= [.. merged.Typedefs.Select(t => t.Name)];
            return _typedefNames.Contains(type.Name) ? type.Name : $"{(type.Kind == RecordKind.Union ? "union" : "struct")} {type.Name}";
        }
        if (_aliases.TryGetValue(type.Name, out var existing))
            return existing;

        var (owner, field) = merged.Types
            .SelectMany(t => t.Fields.Where(f => !f.IsAnonymousMember).Select(f => (Owner: t, Field: f)))
            .FirstOrDefault(x => EmittedRecords.ElementRecord(x.Field.Type) == type.Name);

        string alias;
        if (owner is null)
        {
            // Not a named field's type: an anonymous member. Reached only through its parent.
            alias = type.Parent is { } parent && merged.FindType(parent) is { } p ? TypeExpression(p) : type.Name;
            _aliases[type.Name] = alias;
            return alias;
        }

        alias = "cimport_" + Sanitize(type.Name);
        _aliases[type.Name] = alias;
        var ownerExpr = TypeExpression(owner);
        // The element type of an array field: one [0] per dimension.
        var element = "";
        for (var t = field.Type.Desugar(); t.Kind == TypeRefKind.Array; t = t.Element!.Desugar())
            element += "[0]";
        _aliasLines.Add((Condition(owner.Name, owner.Header), $"typedef __typeof__((({ownerExpr} *)0)->{field.Name}{element}) {alias};"));
        return alias;
    }

    private static string Sanitize(string name)
    {
        var sb = new StringBuilder();
        foreach (var ch in name.Replace("::", "_").Replace("@", "anon"))
            sb.Append(char.IsAsciiLetterOrDigit(ch) || ch == '_' ? ch : '_');
        return sb.ToString();
    }

    private static string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");

    /// <summary>Sizes, alignments and offsets: plain decimal, one value or a per-ABI choice.</summary>
    private static string Plain(PerAbi<long> value)
    {
        var text = value.Values.Select(v => v.ToString(CultureInfo.InvariantCulture)).ToList();
        return value.IsUniform ? text[0] : $"VLCLR_ABI({string.Join(", ", text)})";
    }

    private static string Value(IEnumerable<long> values, bool unsigned = false)
    {
        var list = values.ToList();
        if (list.Distinct().Count() == 1)
            return Literal(list[0], unsigned);
        return $"VLCLR_ABI({string.Join(", ", list.Select(v => Literal(v, unsigned)))})";
    }

    private static string Literal(long value, bool unsigned)
    {
        if (unsigned)
            return unchecked((ulong)value).ToString(CultureInfo.InvariantCulture) + "ULL";
        if (value == long.MinValue)
            return "(-9223372036854775807LL - 1)";
        return value.ToString(CultureInfo.InvariantCulture) + "LL";
    }
}
