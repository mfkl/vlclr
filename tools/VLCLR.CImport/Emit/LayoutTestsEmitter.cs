using System.Globalization;
using System.Text;
using VLCLR.CImport.Merge;
using VLCLR.CImport.Model;
using VLCLR.CImport.Naming;

namespace VLCLR.CImport.Emit;

/// <param name="Namespace">Namespace of the generated test class, e.g. <c>VLCLR.Tests.Interop</c>.</param>
/// <param name="ClassName">Name of the generated test class, e.g. <c>InteropLayoutTests</c>.</param>
public sealed record LayoutTestOptions(string Namespace, string ClassName);

/// <summary>
/// Writes xunit tests that check the generated C# structs against the snapshot on
/// the running ABI: <c>SizeOf</c>, <c>Unsafe.SizeOf</c>, every member offset, and
/// the exact bits each bitfield property touches. One <c>[Fact]</c>
/// <c>{CSharpType}_Layout</c> per emitted record (the suffix keeps the method name
/// from shadowing the type inside the class). Members the C# emitter skipped
/// (<paramref name="skipped"/>) are left out. Generated types are written in
/// full (<c>global::Namespace.Type</c>): names like <c>Guid</c> or
/// <c>Mutex</c> would be ambiguous with the BCL's under implicit usings.
/// </summary>
public sealed class LayoutTestEmitter(MergedSnapshot merged, INameMap names, LayoutTestOptions options, IReadOnlyCollection<SkippedSymbol>? skipped = null)
{
    private readonly StringBuilder _sb = new();
    private readonly HashSet<string> _skippedFields = [.. (skipped ?? []).Where(s => s.Kind == "field").Select(s => s.Symbol)];
    private readonly Dictionary<string, MergedType> _records = merged.Types.ToDictionary(t => t.Name, StringComparer.Ordinal);

    public string Emit()
    {
        _sb.Clear();
        Line("// <auto-generated>");
        Line($"// Generated by VLCLR.CImport from the VLC headers at commit {merged.VlcCommit}. Do not edit.");
        Line("// </auto-generated>");
        Line();
        Line("using System;");
        Line("using System.Runtime.CompilerServices;");
        Line("using System.Runtime.InteropServices;");
        Line("using System.Runtime.Versioning;");
        Line("using Xunit;");
        Line();
        Line($"namespace {options.Namespace};");
        Line();
        Line($"public unsafe class {options.ClassName}");
        Line("{");

        foreach (var type in EmittedRecords.Select(merged))
        {
            WriteRecord(type);
            Line();
        }

        WriteHelpers();
        Line("}");
        return _sb.ToString();
    }

    private void Line(string text = "") => _sb.Append(text).Append('\n');

    private void WriteRecord(MergedType type)
    {
        var typeName = names.Type(type.Name);
        var csType = Qualified(typeName);
        Line("    [Fact]");
        // Only the analyzer cares: the test is managed code and runs anywhere.
        if (merged.PlatformsOf(type.Name) is { } platforms)
            Line(platforms is [Abis.Windows] ? "    [SupportedOSPlatform(\"windows\")]" : "    [UnsupportedOSPlatform(\"windows\")]");
        Line($"    public void {typeName}_Layout()");
        Line("    {");
        Line($"        var s = default({csType});");
        Line($"        AssertEqual({Abi(type.Size!)}, {csType}.SizeOf, \"{Escape(type.Name)} sizeof\");");
        Line($"        AssertEqual({type.Size!.Values.Max()}, Unsafe.SizeOf<{csType}>(), \"{Escape(type.Name)} Unsafe.SizeOf\");");

        var members = type.Members.Where(m => !_skippedFields.Contains($"{type.Name}.{m.Name}")).ToList();
        foreach (var member in members.Where(m => !m.IsBitfield))
        {
            var csName = names.Field(member.DeclaringType, member.Name);
            var label = $"\"{Escape(type.Name)}.{Escape(member.Name)} offset\"";
            // The C# emitter returns these as a pointer to the member.
            if (EmittedRecords.IsAbiSizedRecord(member.Type, _records))
                Line($"        AssertEqual({Abi(member.Offset)}, PointerOffset(ref s, s.{csName}), {label});");
            // Pointers can't be generic arguments: pin the member and subtract addresses.
            else if (member.Type.Desugar().Kind == TypeRefKind.Pointer)
                Line($"        {{ ref var r = ref s.{csName}; fixed (void* p = &r) AssertEqual({Abi(member.Offset)}, PointerOffset(ref s, p), {label}); }}");
            else
                Line($"        AssertEqual({Abi(member.Offset)}, Offset(ref s, ref s.{csName}), {label});");
        }

        foreach (var member in members.Where(m => m.IsBitfield))
        {
            var csName = names.Field(member.DeclaringType, member.Name);
            var value = AllOnes(member);
            var label = $"{Escape(type.Name)}.{Escape(member.Name)}";
            Line("        {");
            Line($"            var b = default({csType});");
            Line($"            var ones = {value};");
            Line($"            b.{csName} = ones;");
            Line($"            AssertBits(ref b, {Abi(member.BitOffset!)}, {member.BitWidth}, \"{label}\");");
            Line($"            Assert.Equal(ones, b.{csName});");
            Line("        }");
        }

        Line("    }");
    }

    /// <summary>A C# expression for the all-ones value of a bitfield property, typed like the property.</summary>
    private string AllOnes(MergedField field)
    {
        var width = field.BitWidth!.Value;
        var mask = width >= 64 ? ulong.MaxValue : (1UL << width) - 1;
        var hex = "0x" + mask.ToString("X", CultureInfo.InvariantCulture) + (width > 31 ? "UL" : "");

        var type = field.Type.Desugar();
        switch (type.Kind)
        {
            case TypeRefKind.Builtin:
                if (type.Builtin == BuiltinType.Bool)
                    return "true";
                // C long is 32 bits on windows: the C# emitter maps it to CLong / CULong.
                if (type.Builtin == BuiltinType.Long)
                    return "new CLong(-1)";
                if (type.Builtin == BuiltinType.ULong)
                    return $"new CULong(unchecked((nuint){hex}))";
                var (cs, signed) = Map(type.Builtin!.Value);
                return signed ? $"({cs})(-1)" : $"unchecked(({cs}){hex})";

            case TypeRefKind.Enum:
                var enumName = Qualified(names.Type(type.Name!));
                var declared = merged.Enums.FirstOrDefault(e => e.Name == type.Name);
                var enumSigned = declared is not null
                    && declared.UnderlyingType.Values[0].Desugar().Builtin is BuiltinType.Char or BuiltinType.SChar or BuiltinType.Short or BuiltinType.Int or BuiltinType.Long or BuiltinType.LongLong;
                return enumSigned ? $"unchecked(({enumName})(-1))" : $"unchecked(({enumName}){hex})";

            default:
                throw new InvalidOperationException($"Bitfield '{field.DeclaringType}.{field.Name}' has unsupported type {type.Kind}.");
        }
    }

    private static (string Name, bool Signed) Map(BuiltinType builtin) => builtin switch
    {
        BuiltinType.Char or BuiltinType.UChar => ("byte", false),
        BuiltinType.SChar => ("sbyte", true),
        BuiltinType.Short => ("short", true),
        BuiltinType.UShort => ("ushort", false),
        BuiltinType.Int => ("int", true),
        BuiltinType.UInt => ("uint", false),
        BuiltinType.LongLong => ("long", true),
        BuiltinType.ULongLong => ("ulong", false),
        _ => throw new InvalidOperationException($"Unsupported bitfield type {builtin}."),
    };

    private string Qualified(string csType) => $"global::{names.Namespace}.{csType}";

    private static string Abi(PerAbi<long> value)
        => value.IsUniform
            ? value[0].ToString(CultureInfo.InvariantCulture)
            : $"Abi({value[0].ToString(CultureInfo.InvariantCulture)}, {value[1].ToString(CultureInfo.InvariantCulture)})";

    private static string Escape(string text) => text.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private void WriteHelpers()
    {
        Line("    // Windows value, then SysV value, for the ABI the tests run on.");
        Line("    private static int Abi(int w, int s) => OperatingSystem.IsWindows() ? w : s;");
        Line();
        Line("    private static nint Offset<TOwner, TField>(ref TOwner owner, ref TField field)");
        Line("        => Unsafe.ByteOffset(ref Unsafe.As<TOwner, byte>(ref owner), ref Unsafe.As<TField, byte>(ref field));");
        Line();
        Line("    private static nint PointerOffset<TOwner>(ref TOwner owner, void* field)");
        Line("        => (nint)((byte*)field - (byte*)Unsafe.AsPointer(ref owner));");
        Line();
        Line("    private static void AssertEqual(long expected, long actual, string what)");
        Line("    {");
        Line("        if (expected != actual)");
        Line("            Assert.Fail($\"{what}: expected {expected}, actual {actual}\");");
        Line("    }");
        Line();
        Line("    // Exactly the bits [bitOffset, bitOffset + bitWidth) of the zeroed struct may be set.");
        Line("    private static void AssertBits<T>(ref T value, long bitOffset, int bitWidth, string what)");
        Line("    {");
        Line("        var bytes = new ReadOnlySpan<byte>(Unsafe.AsPointer(ref value), Unsafe.SizeOf<T>());");
        Line("        for (var bit = 0; bit < bytes.Length * 8; bit++)");
        Line("        {");
        Line("            var expected = bit >= bitOffset && bit < bitOffset + bitWidth;");
        Line("            var actual = ((bytes[bit / 8] >> (bit % 8)) & 1) != 0;");
        Line("            if (expected != actual)");
        Line("                Assert.Fail($\"{what}: bit {bit} is {(actual ? \"set\" : \"clear\")}, expected the field to occupy bits {bitOffset}..{bitOffset + bitWidth - 1}\");");
        Line("        }");
        Line("    }");
    }
}
